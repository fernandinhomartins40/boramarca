package br.com.boramarca.balcao

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.app.Service
import android.content.Context
import android.content.Intent
import android.content.pm.ServiceInfo
import android.media.AudioAttributes
import android.media.AudioFormat
import android.media.AudioTrack
import android.os.Build
import android.os.Handler
import android.os.IBinder
import android.os.Looper
import android.os.PowerManager
import androidx.core.app.NotificationCompat
import androidx.core.app.ServiceCompat

/**
 * Foreground service of type "microphone". Android 14+ rules: declared type,
 * FOREGROUND_SERVICE_MICROPHONE, RECORD_AUDIO granted and started while the app is in the
 * foreground. It does not record by itself: it keeps the process allowed to use the microphone
 * with the screen locked, where the JS side runs Porcupine and the speech recognizer. Shows the
 * fixed "Bora Marca está ouvindo" notification with a "Pausar" action, holds a partial wake lock
 * and, when enabled, plays a near-silent tone every 4 minutes so Bluetooth speakers do not
 * switch themselves off.
 */
class BalcaoService : Service() {
  private val handler = Handler(Looper.getMainLooper())
  private var wakeLock: PowerManager.WakeLock? = null
  private var stopReason = "stopped"

  private val keepAwakeTick = object : Runnable {
    override fun run() {
      if (keepSpeakerAwake(this@BalcaoService)) playInaudibleTone()
      handler.postDelayed(this, KEEP_AWAKE_MS)
    }
  }

  override fun onBind(intent: Intent?): IBinder? = null

  override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
    if (intent?.action == ACTION_PAUSE) {
      stopReason = "paused"
      stopSelf()
      return START_NOT_STICKY
    }
    val title = intent?.getStringExtra(EXTRA_TITLE) ?: "Bora Marca está ouvindo"
    val text = intent?.getStringExtra(EXTRA_TEXT) ?: "Diga Ei, Bora Marca."
    val pause = intent?.getStringExtra(EXTRA_PAUSE) ?: "Pausar"
    val type =
      if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) ServiceInfo.FOREGROUND_SERVICE_TYPE_MICROPHONE else 0
    ServiceCompat.startForeground(this, NOTIFICATION_ID, buildNotification(title, text, pause), type)
    if (!running) {
      running = true
      val pm = getSystemService(Context.POWER_SERVICE) as PowerManager
      wakeLock = pm.newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "BoraMarca:balcao").apply {
        setReferenceCounted(false)
        acquire()
      }
      handler.postDelayed(keepAwakeTick, KEEP_AWAKE_MS)
      listener?.invoke(true, "started")
    }
    // not sticky: Android 14+ forbids starting a microphone service from the background anyway
    return START_NOT_STICKY
  }

  override fun onDestroy() {
    handler.removeCallbacks(keepAwakeTick)
    wakeLock?.let { if (it.isHeld) it.release() }
    wakeLock = null
    if (running) {
      running = false
      listener?.invoke(false, stopReason)
    }
    super.onDestroy()
  }

  private fun buildNotification(title: String, text: String, pause: String): Notification {
    val nm = getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
      nm.createNotificationChannel(
        NotificationChannel(CHANNEL_ID, "Modo Balcão", NotificationManager.IMPORTANCE_LOW).apply {
          description = "Aviso fixo enquanto o balcão está ouvindo"
          setShowBadge(false)
        },
      )
    }
    val flags = PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
    val open = packageManager.getLaunchIntentForPackage(packageName)?.let {
      PendingIntent.getActivity(this, 0, it, flags)
    }
    val pauseIntent = PendingIntent.getService(
      this, 1, Intent(this, BalcaoService::class.java).setAction(ACTION_PAUSE), flags,
    )
    // monochrome icon generated by the expo-notifications plugin; falls back to the app icon
    val icon = resources.getIdentifier("notification_icon", "drawable", packageName)
      .takeIf { it != 0 } ?: applicationInfo.icon
    return NotificationCompat.Builder(this, CHANNEL_ID)
      .setSmallIcon(icon)
      .setContentTitle(title)
      .setContentText(text)
      .setOngoing(true)
      .setCategory(NotificationCompat.CATEGORY_SERVICE)
      .setForegroundServiceBehavior(NotificationCompat.FOREGROUND_SERVICE_IMMEDIATE)
      .setContentIntent(open)
      .addAction(0, pause, pauseIntent)
      .build()
  }

  /** 0.5 s of a 1-LSB square wave: keeps the A2DP stream active without anything audible. */
  private fun playInaudibleTone() {
    try {
      val rate = 44100
      val samples = ShortArray(rate / 2) { if (it % 2 == 0) 1 else -1 }
      val track = AudioTrack.Builder()
        .setAudioAttributes(
          AudioAttributes.Builder()
            .setUsage(AudioAttributes.USAGE_MEDIA)
            .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build(),
        )
        .setAudioFormat(
          AudioFormat.Builder()
            .setEncoding(AudioFormat.ENCODING_PCM_16BIT)
            .setSampleRate(rate)
            .setChannelMask(AudioFormat.CHANNEL_OUT_MONO)
            .build(),
        )
        .setTransferMode(AudioTrack.MODE_STATIC)
        .setBufferSizeInBytes(samples.size * 2)
        .build()
      track.write(samples, 0, samples.size)
      track.play()
      handler.postDelayed({ track.release() }, 1000)
    } catch (_: Exception) {
      // speaker keep-alive is best effort
    }
  }

  companion object {
    const val CHANNEL_ID = "balcao"
    const val NOTIFICATION_ID = 4210
    const val ACTION_PAUSE = "br.com.boramarca.balcao.PAUSE"
    const val EXTRA_TITLE = "title"
    const val EXTRA_TEXT = "text"
    const val EXTRA_PAUSE = "pause"
    const val KEEP_AWAKE_MS = 4 * 60 * 1000L
    private const val PREFS = "boramarca_balcao"
    private const val KEY_KEEP_AWAKE = "keepSpeakerAwake"

    @Volatile
    var running = false
      private set

    /** (running, reason): set by the Expo module to forward to JS. */
    var listener: ((Boolean, String) -> Unit)? = null

    fun keepSpeakerAwake(context: Context) =
      context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getBoolean(KEY_KEEP_AWAKE, true)

    fun setKeepSpeakerAwake(context: Context, enabled: Boolean) =
      context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit()
        .putBoolean(KEY_KEEP_AWAKE, enabled).apply()
  }
}
